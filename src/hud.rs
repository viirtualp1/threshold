pub type Text = [[u32; 4]; 3];

pub fn pack(text: &str) -> Text {
    let mut words = [[0; 4]; 3];
    for (index, byte) in text.bytes().take(48).enumerate() {
        words[index / 16][(index / 4) % 4] |= u32::from(byte) << (index % 4 * 8);
    }
    words
}

pub fn scale_label(size: f32) -> &'static str {
    if size > 5.0 {
        "BODY SCALE  10X"
    } else if size > 0.5 {
        "BODY SCALE  1X"
    } else if size > 0.05 {
        "BODY SCALE  0.1X"
    } else if size > 0.005 {
        "BODY SCALE  0.01X"
    } else {
        "BODY SCALE  0.001X"
    }
}

